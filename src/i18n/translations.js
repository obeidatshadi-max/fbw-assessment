export const LANGS = ['en', 'ar', 'fr'];
export const RTL_LANGS = ['ar'];

export function dirFor(lang) {
  return RTL_LANGS.includes(lang) ? 'rtl' : 'ltr';
}

// Localizes a value that may be a plain string (untranslated / test fixture)
// or a { en, ar, fr } object. Falls back to English, then to the raw value.
export function L(value, lang) {
  if (value == null || typeof value === 'string') return value;
  return value[lang] ?? value.en ?? value;
}

// Interpolates {placeholders} in a translated string with the given vars.
export function tf(lang, path, vars = {}) {
  const raw = t(lang, path);
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

export function t(lang, path) {
  const dict = UI[lang] || UI.en;
  const fromDict = getPath(dict, path);
  if (fromDict !== undefined) return fromDict;
  return getPath(UI.en, path) ?? path;
}

function getPath(obj, path) {
  return path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);
}

